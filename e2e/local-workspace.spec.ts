test('recovers an open draft under a new identity when a remote tombstone removes its saved record', async ({ page }) => {
  await openSidebarIfNeeded(page)
  await page.locator('.sidebar').getByRole('button', { name: 'GET naas', exact: true }).click()
  await page.getByLabel('Request URL').fill('https://example.com/remote-deletion-local-edits')
  const id = await page.evaluate(() => localStorage.getItem('active-editor-draft'))
  await expect.poll(async () => (await readLocalRows<{ id: string; url: string }>(page, 'editorDrafts')).find((r) => r.id === id)?.url).toBe('https://example.com/remote-deletion-local-edits')
  // Simulate the atomic database result of an authenticated encrypted tombstone.
  await page.evaluate((oldId) => new Promise<void>((resolve, reject) => {
    const opening = indexedDB.open('open-request-workbench')
    opening.onsuccess = () => {
      const database = opening.result
      const tx = database.transaction(['requests', 'syncedEntities'], 'readwrite')
      tx.objectStore('requests').delete(oldId!)
      tx.objectStore('syncedEntities').put({ id: `request:${oldId}`, entityType: 'request', entityId: oldId, deleted: true, syncedAt: Date.now() })
      tx.oncomplete = () => { database.close(); resolve() }
      tx.onerror = () => { database.close(); reject(tx.error) }
    }
    opening.onerror = () => reject(opening.error)
  }), id)
  await page.reload()
  await expect(page.getByLabel('Request URL')).toHaveValue('https://example.com/remote-deletion-local-edits')
  expect(await page.evaluate(() => localStorage.getItem('active-editor-draft'))).not.toBe(id)
  expect((await readLocalRows<{ id: string }>(page, 'editorDrafts')).some((r) => r.id === id)).toBe(false)
  expect(await readSyncOutbox(page)).toEqual([])
})

